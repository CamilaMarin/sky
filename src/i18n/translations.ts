export const translations: Record<Language, Record<TranslationKey, string>> = { en, es }

export function translate(language: Language, key: TranslationKey, values: Record<string, string | number> = {}): string {
  const text = translations[language]?.[key] ?? en[key]
  return text.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match))
}
